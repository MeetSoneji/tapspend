// Layer 1 configuration (fork-time): app.config.properties at repo root.
val appConfig = Properties().apply {
    rootProject.file("app.config.properties").inputStream().use { load(it) }
}
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "com.meetsoneji.tapspend"
    compileSdk = 35

    defaultConfig {
        applicationId = appConfig.getProperty("app.id")
        minSdk = 26
        targetSdk = 35
        versionCode = 3
        versionName = "1.1.0"
        resValue("string", "app_name", appConfig.getProperty("app.name"))
        resValue("string", "app_tagline", appConfig.getProperty("app.tagline"))
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (keystoreProps.getProperty("storeFile") != null) {
            create("release") {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfigs.findByName("release")?.let { signingConfig = it }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
        isCoreLibraryDesugaringEnabled = true
    }
    kotlinOptions { jvmTarget = "17" }

    buildFeatures {
        compose = true
        buildConfig = true
        resValues = true
    }

    packaging {
        resources.excludes += setOf("/META-INF/{AL2.0,LGPL2.1}", "META-INF/versions/**")
    }

    lint {
        warningsAsErrors = false
        abortOnError = true
        checkReleaseBuilds = true
    }

    testOptions { unitTests.isReturnDefaultValues = true }
}

// Static shortcuts need the real applicationId (it differs for debug builds because of the .debug suffix).
androidComponents {
    onVariants { variant ->
        variant.resValues.put(
            variant.makeResValueKey("string", "app_package"),
            variant.applicationId.map { com.android.build.api.variant.ResValue(it, null) },
        )
    }
}

